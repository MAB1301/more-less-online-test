import assert from 'node:assert/strict';
import {createAccountSession} from '../assets/account/session.mjs';
const entries=new Map([['moreless_online_session_v1','room']]);
const storage={getItem:k=>entries.get(k)||null,setItem:(k,v)=>entries.set(k,v),removeItem:k=>entries.delete(k)};
let stamp=0,refreshes=0;const calls=[];
const response=(status,body)=>({ok:status<400,status,text:async()=>body===null?'':JSON.stringify(body)});
const identity=(uid='guest',guest=true)=>({access_token:'access',refresh_token:'refresh',expires_in:120,user:{id:uid,is_anonymous:guest}});
let handler=async(path)=>path.includes('refresh_token')?(refreshes++,response(200,identity())):response(200,identity());
const client=createAccountSession({url:'https://test.invalid',key:'public',storage,now:()=>stamp,fetchImpl:async(url,opt)=>{calls.push({url,opt});return handler(url,opt)}});
assert.equal((await client.guest()).uid,'guest');
assert.equal(calls.length,1);
await client.guest();assert.equal(calls.length,1,'guest reuses identity');
stamp=90000;await Promise.all([client.current(),client.current()]);assert.equal(refreshes,1,'concurrent requests share refresh');
assert.equal(entries.get('moreless_online_session_v1'),'room','auth storage never replaces room');
await assert.rejects(()=>client.profile('hello','Name'),/bestätigten/);
await assert.rejects(()=>client.register('a@b.de','password'),/upgrade/);
handler=async(url,opt)=>{assert(url.endsWith('/auth/v1/user'));assert.equal(opt.method,'PUT');return response(200,{id:'guest',is_anonymous:true})};
await client.upgrade('a@b.de','password');assert.equal((await client.current()).guest,true,'email update does not prematurely mark guest as confirmed');
stamp=180000;handler=async()=>response(200,identity('different'));
await assert.rejects(()=>client.current(),/Identität/);
assert.equal(JSON.parse(entries.get('ml_account_auth_v1')).uid,'guest');
handler=async()=>response(200,identity('account',false));await client.login('a@b.de','password');
handler=async()=>response(204,null);await client.acceptFriend('friend');await client.logout();
assert.equal(await client.current(),null);assert.equal(entries.get('moreless_online_session_v1'),'room');
const clean=createAccountSession({url:'https://test.invalid',key:'public',storage,fetchImpl:async()=>response(200,{user:{id:'new'}})});
assert.deepEqual(await clean.register('a@b.de','password'),{session:null,confirmationRequired:true});
console.log('OK: isolated account persistence, refresh coordination, identity checks, guest upgrade, confirmation and empty mutation responses');
